/**
 * Стенд оценки качества обращается к тому же `RATE_LIMIT_RPM` (docs/07-integration.md §7.8,
 * `RateLimitGuard`), что и любой другой клиент API — залп запросов без пауз на сотнях записей
 * выборки упёрся бы в собственное ограничение частоты сервиса и дал бы `429` вместо результата
 * определения, искажая метрики стенда ложными ошибками прогона. Интервал ниже — консервативная
 * пауза (задел даже под уменьшенный `RATE_LIMIT_RPM`, если стенд запущен на контуре с более
 * строгой настройкой, чем демонстрационная по умолчанию, 120/мин).
 */
export const EVAL_REQUEST_INTERVAL_MS = 700;

export function sleep(ms: number): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms));
}
