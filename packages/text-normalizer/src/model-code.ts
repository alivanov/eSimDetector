/**
 * Распознавание сервисного кода модели по вендорским шаблонам (docs/04-matching-algorithm.md,
 * §4.5): `SM-S928B` (Samsung), `CPH2451` (Oppo/Realme/OnePlus на общей платформе), `23090RA98G`
 * (Xiaomi/Redmi/POCO). Такой ввод — самый точный вид запроса, и его нельзя отправлять в
 * нечёткий поиск (AGENTS.md, предметное правило 4): распознанный код сразу ищется по индексу
 * кодов справочника (это задача `fuzzy-matcher`/`matching`, не этого пакета).
 *
 * Проверка выполняется на исходной строке целиком, ДО общего конвейера нормализации:
 * `unifySeparators` превращает дефис в пробел, а `splitLettersAndDigits` дробит код на
 * куски по границе "буква ↔ цифра" (`SM-S928B` → `sm s 928 b`) — форма, по которой уже
 * невозможно восстановить исходный код. Поэтому `detectModelCode` вызывается конвейером
 * `normalizeQuery` на `raw` до этих шагов (см. normalize-query.ts).
 *
 * Ограничение: шаблоны рассчитаны на запрос, состоящий ТОЛЬКО из кода (без сопутствующих
 * слов) — это соответствует реальному вводу пользователя, скопировавшего код из настроек
 * телефона или коробки. Код, встретившийся внутри более длинной фразы ("самсунг SM-S928B"),
 * этой функцией не распознаётся и уходит в обычный слотовый разбор.
 */

const MODEL_CODE_PATTERNS: readonly RegExp[] = [
  // Samsung: SM-S928B, SM-A346E, SM-F731B, SM-X716B.
  /^SM-[A-Z]\d{3,4}[A-Z0-9]{0,3}$/,
  // Oppo / Realme / OnePlus (общая платформа выпуска): CPH2451, CPH2173.
  /^CPH\d{4}$/,
  // Xiaomi / Redmi / POCO: 23090RA98G, 2201116SG — цифры года-волны выпуска, буквенный
  // код проекта/варианта, необязательный числовой и буквенный хвост ревизии.
  /^\d{4,7}[A-Z]{1,4}(?:\d{1,3}[A-Z]{0,3})?$/,
];

/**
 * Возвращает нормализованный (обрезанный, в верхнем регистре) сервисный код, если весь
 * входной текст ему соответствует, иначе `undefined`.
 */
export function detectModelCode(input: string): string | undefined {
  const candidate = input.trim().toUpperCase();
  if (candidate.length === 0) {
    return undefined;
  }

  const matches = MODEL_CODE_PATTERNS.some((pattern) => pattern.test(candidate));
  return matches ? candidate : undefined;
}
